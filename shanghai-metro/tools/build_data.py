def dist_km(a, b):
    (lo1, la1), (lo2, la2) = S[a], S[b]
    k = math.pi / 180
    dx = (lo2 - lo1) * math.cos((la1 + la2) / 2 * k) * 111.32
    dy = (la2 - la1) * 110.57
    return math.hypot(dx, dy)


def main():
    cc = OpenCC("s2t")
    used = set()
    for _, _, _, services, _, _ in LINES:
        for svc in services:
            for n in svc:
                if n not in S:
                    raise SystemExit(f"缺少座標：{n}")
                used.add(n)
            for a, b in zip(svc, svc[1:]):
                d = dist_km(a, b)
                if d > 16 or d < 0.3:
                    print(f"注意：{a} → {b} 間距 {d:.2f} km")
    unused = set(S) - used
    if unused:
        raise SystemExit(f"未使用的站點：{unused}")

    names = sorted(used, key=lambda n: (S[n][1], S[n][0]))
    idx = {n: i for i, n in enumerate(names)}
    stations = []
    for n in names:
        t = cc.convert(n).replace("(6號線)", "（6號線）")
        stations.append({
            "s": n, "t": t, "x": round(S[n][0], 4), "y": round(S[n][1], 4),
            "a": [cc.convert(a) for a in ALIASES.get(n, [])] + ALIASES.get(n, []),
        })
    lines = []
    for lid, name, color, services, speed, kind in LINES:
        lines.append({
            "id": lid, "name": name, "color": color, "speed": speed, "kind": kind,
            "svc": [[idx[n] for n in svc] for svc in services],
        })
    out = os.path.join(os.path.dirname(__file__), "..", "metro-data.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// 由 tools/build_data.py 產生，請勿手動編輯\n")
        f.write("window.METRO=" + json.dumps({"stations": stations, "lines": lines},
                                            ensure_ascii=False, separators=(",", ":")) + ";\n")
    print(f"{len(stations)} 站、{len(lines)} 條路線 → {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
